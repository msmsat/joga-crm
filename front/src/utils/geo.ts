// Валюта студии по стране визита — подсказка в селекте на онбординге, а не факт
// о бизнесе: человек волен её сменить, и в студию уедет то, что он видел, а не
// то, что подставил IP.
//
// Карта перечисляет только НЕ-евровые страны. Так короче и так честнее: евро —
// фолбэк, и выписывать в карту два десятка стран еврозоны значило бы получить
// ровно то же поведение вдвое большим списком. Страна не в карте, страна
// неизвестна (локальный адрес, выход Tor, нет базы GeoIP на сервере) — евро:
// в нём платформа и так выставляет счета студиям.
//
// Состав — страны, где говорят на языках интерфейса (utils/lang.ts): именно
// они могут открыть продукт и узнать его. Языки тянут далеко за Европу —
// испанский приводит всю Латинскую Америку, французский — Западную Африку,
// английский — Карибы и Океанию, — и валюта у каждой из этих стран своя.
//
// Коды валют берутся ТОЛЬКО из CURRENCIES (utils/currency.ts): валюта, которой
// нет в списке выбора, подставится в селект пустой строкой — человек не увидит,
// что выбрано. Это и стережёт geo.check.ts.
//
// Self-check:  node src/utils/geo.check.ts

