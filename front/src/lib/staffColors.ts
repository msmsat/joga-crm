// Цвета сотрудников: колонка и занятия мастера в журнале, выбор в его карточке.
//
// Выдаёт цвет СЕРВЕР — первый свободный в студии (back/services/members.py,
// STAFF_PALETTE), здесь копия той же палитры для выбора в карточке. Порядок
// значим: соседние цвета — самые непохожие, первые достаются первым мастерам.
//
// Цветов блоков журнала здесь нет и быть не должно: персик и кирпич — это
// перерыв, малина — выходной, аква — «время студии» (StaffBlockCard.css).
// Мастер в таком цвете выглядел бы блоком без занятия; сервер такой цвет не
// принимает, а у кого он остался с прежних времён — меняет при запуске
// (back/services/staff_colors.py).

export const STAFF_PALETTE = [
  '#4A80C4', // синий
  '#5BAB72', // зелёный
  '#7B6CD4', // фиолетовый
  '#E0A030', // янтарь
  '#B062C0', // орхидея
  '#8FA53A', // олива
  '#5E7389', // сланец
  '#8B6F5A', // какао
] as const;

// Цвет сотрудника. Своего нет только у строк, заведённых в обход роутеров
// (сиды), — тогда цвет из палитры по id: стабилен между заходами и не
// съезжает, когда кого-то скрыли фильтром или уволили.
export const staffColor = (s: { id: number; color?: string | null }): string =>
  s.color || STAFF_PALETTE[s.id % STAFF_PALETTE.length];
