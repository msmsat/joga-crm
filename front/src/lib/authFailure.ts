/**
 * Что делать с ответом 401.
 *
 * Глобальный перехват в `api/client.ts` писался под один случай — «наш токен
 * мёртв»: выбросить токен и увести на /login. Но под него попадал и сам вход:
 * на неверную пару email/пароль бэкенд отвечает 401 (routers/auth/login.py),
 * клиент делал `window.location.href = '/login'`, страница перезагружалась —
 * и форма теряла сообщение об ошибке, не успев его отрисовать. Неверный пароль
 * выглядел как «кнопка ничего не делает», а `clearActiveToken()` заодно
 * выкидывал человека из аккаунта, в котором он уже работал.
 *
 * Правило СТРУКТУРНОЕ, а не список ручек: токена не посылали (`auth: false`) —
 * значит 401 пришёл про данные в теле запроса (пароль на `/auth/login`, код на
 * `/auth/login/2fa`, токен из письма на `/auth/invite`), а не про нашу сессию,
 * и гасить её не за что. Новая публичная ручка получает это поведение сама, не
 * вспоминая про перехватчик.
 *
 * Держится `npm run check:auth` (front/scripts/check-auth-401.mjs).
 */

export interface Request401 {
  /** Посылали ли мы `Authorization`; `false` — запрос публичный. */
  auth?: boolean
  /** Вызывающий проверяет ЧУЖОЙ токен (переключатель аккаунтов) и разберёт 401 сам. */
  allowUnauthorized?: boolean
}

export type Reaction401 =
  /** Сессия мертва: выбросить токен и увести на вход. */
  | 'end-session'
  /** Отдать ошибку вызывающему — он покажет её в своей форме. */
  | 'report'

export function reactTo401(options: Request401 = {}): Reaction401 {
  if (options.allowUnauthorized) return 'report'
  if (options.auth === false) return 'report'
  return 'end-session'
}
