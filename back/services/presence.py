"""Кто прямо сейчас открыт на сайте: лендинг, кабинет, мини-приложение.

Счёт идёт в памяти процесса, а не в базе. Присутствие живёт минуту и после
перезапуска никому не нужно: писать его в Postgres значило бы делать запись на
каждого посетителя каждые двадцать секунд ради данных, которые сами себя
стирают через минуту.

ponytail: словарь в памяти ОДНОГО процесса. uvicorn здесь поднимается без
--workers (`back/Dockerfile`), контейнер `api` один, поэтому счётчик тоже один
на всех. Появятся воркеры или вторая реплика api — счётчик станет считать
только свою долю, и присутствие придётся переносить в Redis.
"""
import time

# Поверхности, которые продукт различает. Всё остальное отбрасывается: иначе
# любой желающий дорисовал бы в панель строку с собственным названием.
SURFACES = ("landing", "crm", "miniapp")

# Сколько человек считается живым после последнего сигнала. Клиент шлёт сигнал
# раз в 20 секунд — одна потерянная отправка не выкидывает его из счётчика.
TTL_SECONDS = 60

# (поверхность, идентификатор браузера) -> момент последнего сигнала.
_seen: dict[tuple[str, str], float] = {}


def _prune(now: float) -> None:
    cutoff = now - TTL_SECONDS
    for key in [k for k, at in _seen.items() if at < cutoff]:
        del _seen[key]


def touch(surface: str, key: str) -> None:
    """Отмечает, что человек ещё здесь. Чистит просроченных заодно: без этого
    словарь рос бы до следующего открытия панели, а её могут не открывать днями."""
    if surface not in SURFACES or not key:
        return
    now = time.monotonic()
    _prune(now)
    _seen[(surface, key)] = now


def counts() -> dict[str, int]:
    """Живые по поверхностям плюс общее число ЛЮДЕЙ.

    `total` — не сумма трёх чисел: один человек держит открытыми и кабинет, и
    мини-приложение, и в сумме превратился бы в двоих. Поэтому считаются
    различные идентификаторы.
    """
    _prune(time.monotonic())
    result = {surface: 0 for surface in SURFACES}
    for surface, _key in _seen:
        result[surface] += 1
    result["total"] = len({key for _surface, key in _seen})
    return result
