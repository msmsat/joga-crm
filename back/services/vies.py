"""Сверка номера НДС с VIES — реестром плательщиков ЕС.

Зачем сразу, а не потом. Stripe Tax применяет reverse charge (0 % НДС юрлицу из
другой страны ЕС) по ФОРМАТУ номера, не дожидаясь сверки: `DE000000000` обнуляет
налог ровно так же, как настоящий `DE811907980`. Своя сверка у Stripe идёт
асинхронно и приезжает вебхуком уже ПОСЛЕ оплаты, а в test-режиме не выполняется
вовсе — статус остаётся `pending` навсегда. То есть без этой проверки студия,
вписавшая правдоподобный мусор, платит без НДС, а недобор налога по
несуществующему номеру снимут с ПЛАТФОРМЫ: деньги за тариф те же, а 21 % из них
вычтут. Поэтому номер проверяется в момент ввода.

Инвариант всего биллинга: **в Stripe уезжает только ПОДТВЕРЖДЁННЫЙ номер**
(`User.billing_vat_verified`). На нём стоит вся остальная цепочка — оформление
отправляет номер, ничего больше не перепроверяя
(routers/billing/checkout._ensure_customer).

Что делаем, когда реестр молчит. Не отказываем: узел отдельной страны лежит
регулярно, и терять из-за этого покупателя нельзя. Номер с верным ФОРМАТОМ
принимаем и храним неподтверждённым, а плательщику выставляем ПОЛНЫЙ НДС — то
есть ошибаемся в сторону переплаты налога, а не недобора. Сверку повторяет
фоновый проход (routers/billing/webhook.recheck_vat_numbers), и по её успеху
номер начинает работать сам. Уже уплаченный налог за прошлый счёт возвращает
поддержка — об этом плательщику говорит форма реквизитов.

Вебхук `customer.tax_id.updated` при этом остаётся: номер могут аннулировать уже
после нашей проверки, и снятие по сверке Stripe — вторая линия, а не дубль.

Сеть: официальный REST VIES. Поля взяты с ЖИВОГО ответа сервиса, не из доков —
`isValid` + `userError`, и HTTP 200 приходит в том числе на «номер неверный».
"""
import asyncio
import logging
import re
import ssl

import aiohttp
import certifi

logger = logging.getLogger(__name__)

_URL = "https://ec.europa.eu/taxation_customs/vies/rest-api/ms/{ms}/vat/{number}"
# VIES отвечает медленно и неровно. 10 секунд — потолок, за которым форма
# реквизитов начинает выглядеть зависшей; не ответил за них — считаем сервис
# недоступным, а не номер плохим.
_TIMEOUT = aiohttp.ClientTimeout(total=10)

# Страны, у которых номер НДС вообще спрашивается, — 27 членов ЕС и только они.
#
# Снаружи ЕС номер не спрашиваем: сверить его нечем (VIES знает только ЕС), и на
# налог он не влияет — продажа за пределы ЕС вне области европейского НДС,
# место поставки определяет СТРАНА покупателя, а не его номер. То есть хранить
# там было бы нечего, кроме непроверяемой строки, которая потом печатается на
# фискальном документе. Появятся налоговые регистрации в GB/CH/NO — вернуть их
# сюда можно будет только вместе с их реестрами.
#
# Северной Ирландии (XI) здесь нет намеренно: её «европейскость» по НДС касается
# ТОВАРОВ, а мы продаём услуги — по ним она Великобритания, то есть вне ЕС.
EU_VAT_COUNTRIES = frozenset({
    "AT", "BE", "BG", "CY", "CZ", "DE", "DK", "EE", "ES", "FI", "FR", "GR", "HR",
    "HU", "IE", "IT", "LT", "LU", "LV", "MT", "NL", "PL", "PT", "RO", "SE", "SI",
    "SK",
})


# Формат номера НДС по странам ЕС (без префикса страны — он сверяется отдельно,
# см. router._vat_for_country). Источник — официальные спецификации VIES.
#
# Формат НЕ доказывает существование номера и подменой сверки не является: он
# отсекает опечатки и заведомый мусор, и только. Нужен ровно для одного случая —
# когда реестр не отвечает: тогда номер с верным форматом мы принимаем и храним
# НЕПОДТВЕРЖДЁННЫМ, а плательщику выставляем полный НДС, пока сверка не пройдёт.
_FORMATS: dict[str, str] = {
    "AT": r"U\d{8}",
    "BE": r"[01]\d{9}",
    "BG": r"\d{9,10}",
    "CY": r"\d{8}[A-Z]",
    "CZ": r"\d{8,10}",
    "DE": r"\d{9}",
    "DK": r"\d{8}",
    "EE": r"\d{9}",
    "ES": r"[A-Z0-9]\d{7}[A-Z0-9]",
    "FI": r"\d{8}",
    "FR": r"[A-Z0-9]{2}\d{9}",
    "GR": r"\d{9}",
    "HR": r"\d{11}",
    "HU": r"\d{8}",
    "IE": r"(\d{7}[A-W]{1,2}|\d[A-Z*+]\d{5}[A-W])",
    "IT": r"\d{11}",
    "LT": r"(\d{9}|\d{12})",
    "LU": r"\d{8}",
    "LV": r"\d{11}",
    "MT": r"\d{8}",
    "NL": r"\d{9}B\d{2}",
    "PL": r"\d{10}",
    "PT": r"\d{9}",
    "RO": r"\d{2,10}",
    "SE": r"\d{12}",
    "SI": r"\d{8}",
    "SK": r"\d{10}",
}


def format_ok(country: str, vat_id: str) -> bool:
    """Похож ли номер на настоящий номер НДС этой страны.

    Страна вне ЕС или без описанного формата — True: придумывать правило там, где
    его нет, значило бы отвергать законные номера. Регистр приводим сами: люди
    пишут номер и строчными, VIES такой принимает.
    """
    pattern = _FORMATS.get(country)
    if pattern is None:
        return True
    body = vat_id[len(vat_prefix(country)):].upper()
    return re.fullmatch(pattern, body) is not None


# Пул заведомо ДЕЙСТВИТЕЛЬНЫХ номеров для проверки живости сервиса. Каждая страна
# ЕС отвечает за свой узел сама, и падение одного — рутина, а не авария: реестры
# Германии и Франции лежат регулярно. Поэтому живость проверяется пулом с условием
# ИЛИ (ответил хоть один → сеть, TLS и шлюз VIES в порядке), а не одним номером:
# единственная проба означала бы «прод закрыт в день техработ у чужой страны».
#
# Набраны узлы с самой ровной доступностью, крупные публичные компании.
HEALTH_PROBES = {
    "IE": "IE6388047V",       # Google Ireland
    "NL": "NL004495445B01",   # Heineken
    "ES": "ESA28015865",      # Telefónica
    "CZ": "CZ00006947",       # ČEZ
}


def vat_prefix(country: str) -> str:
    """Каким префиксом начинается номер НДС этой страны.

    Совпадает с кодом страны везде, кроме Греции: её код GR, а номера НДС
    начинаются с EL — единственное расхождение в ЕС. Проверять греческий номер
    как «GR» значит не найти его никогда.
    """
    return "EL" if country == "GR" else country

# Ответы, означающие «номера такого нет». Всё ОСТАЛЬНОЕ (MS_UNAVAILABLE,
# SERVICE_UNAVAILABLE, TIMEOUT, *_MAX_CONCURRENT_REQ) — это сбой сервиса, и
# считать его отказом нельзя: реестр одной страны лежит регулярно, а честная
# компания не должна из-за этого получать «номер недействителен».
_REJECTED = {"INVALID", "INVALID_INPUT"}


def verdict(data: dict) -> bool | None:
    """Ответ VIES → True / False / None. Отдельно от запроса, чтобы правило чтения
    можно было проверить без сети — оно и есть самое хрупкое место.

    Формы ответа сняты с ЖИВОГО сервиса: HTTP 200 приходит и на «номер неверный»,
    и на сбой реестра, причём в обоих случаях с `isValid: false`. Различает их
    только `userError`, и читать один `isValid` значит объявлять недействительным
    любой номер, который сегодня некому проверить.
    """
    if data.get("isValid") is True:
        return True
    if data.get("userError") in _REJECTED:
        return False
    return None


async def verify(vat_id: str) -> bool | None:
    """True — номер действителен, False — такого нет, None — VIES не ответил.

    Три состояния, а не два, потому что «недоступен» и «недействителен» ведут к
    разным решениям: первое — попросить повторить, второе — не принимать номер.
    Свести их к False значило бы обвинить честную компанию во лжи всякий раз,
    когда у реестра её страны выходной.
    """
    ms, number = vat_id[:2].upper(), vat_id[2:]
    if not number:
        return False

    try:
        # certifi, а не системное хранилище: цепочка ec.europa.eu на части машин
        # и в голых контейнерах не проверяется (проверено — aiohttp падает с
        # CERTIFICATE_VERIFY_FAILED там, где certifi проходит). Без этого VIES
        # был бы «вечно недоступен», то есть ни один номер НДС не сохранить.
        ssl_context = await asyncio.to_thread(ssl.create_default_context, cafile=certifi.where())
        async with aiohttp.ClientSession(timeout=_TIMEOUT) as session:
            async with session.get(
                _URL.format(ms=ms, number=number), ssl=ssl_context,
            ) as resp:
                if resp.status != 200:
                    logger.warning("VIES: HTTP %s на номер %s", resp.status, vat_id)
                    return None
                # content_type=None — сервис отдаёт JSON, но заголовком иногда
                # объявляет text/plain, и строгая проверка роняла бы разбор.
                data = await resp.json(content_type=None)
    except Exception:
        logger.warning("VIES: сверка номера %s не состоялась", vat_id, exc_info=True)
        return None

    answer = verdict(data)
    if answer is None:
        logger.warning("VIES: номер %s не проверен, ответ %s", vat_id, data.get("userError"))
    return answer


async def health() -> tuple[list[str], list[str]]:
    """Живость сервиса пулом стран → (кто ответил, кто промолчал).

    Пустой первый список = недоступен САМ VIES (нет исходящей сети, не проходит
    цепочка TLS, шлюз лежит). Непустой = сервис доступен, а промолчавшие страны —
    это их собственные узлы, и повод для предупреждения, а не для блокировки.
    Разница принципиальная: во втором случае номера 25 остальных стран сверяются
    как обычно, и закрывать из-за этого боевой режим не за что.

    Опрашиваем параллельно — иначе четыре таймаута по 10 секунд подряд.
    """
    codes = list(HEALTH_PROBES)
    answers = await asyncio.gather(
        *(verify(HEALTH_PROBES[code]) for code in codes), return_exceptions=True,
    )
    alive = [code for code, ok in zip(codes, answers) if ok is True]
    # Ответ «такого номера нет» на заведомо действительный — тоже не «жив»: значит
    # отвечает не реестр, а что-то другое (прокси, портал-заглушка).
    down = [code for code, ok in zip(codes, answers) if ok is not True]
    return alive, down


if __name__ == "__main__":
    # Живая проверка (нужна сеть):  python -m services.vies
    assert vat_prefix("GR") == "EL" and vat_prefix("CZ") == "CZ"
    assert "GB" not in EU_VAT_COUNTRIES and "XI" not in EU_VAT_COUNTRIES
    # Пул живости — только страны ЕС, и номер обязан начинаться префиксом своей.
    assert set(HEALTH_PROBES) <= EU_VAT_COUNTRIES
    assert all(num.startswith(vat_prefix(cc)) for cc, num in HEALTH_PROBES.items())
    assert len(HEALTH_PROBES) >= 3, "пул из двух стран — это почти одна проба"

    # Формат: у каждой страны ЕС он описан, и заведомо верные номера проходят.
    assert set(_FORMATS) == EU_VAT_COUNTRIES, set(_FORMATS) ^ EU_VAT_COUNTRIES
    for _cc, _num in HEALTH_PROBES.items():
        assert format_ok(_cc, _num), (_cc, _num)
    assert format_ok("DE", "DE811907980") and format_ok("DE", "de811907980")
    # Опечатки и мусор отсекаются ДО похода в реестр.
    assert not format_ok("DE", "DE81190798")      # на цифру короче
    assert not format_ok("DE", "DE81190798X")     # буква вместо цифры
    assert not format_ok("NL", "NL004495445X01")  # у NL обязательна B в середине
    assert format_ok("GR", "EL123456789"), "греческий префикс EL, а не GR"
    # Страна вне ЕС — формата нет и придумывать его нечего.
    assert format_ok("US", "чтоугодно")

    _alive, _down = asyncio.run(health())
    assert _alive, f"VIES недоступен целиком (молчат все: {_down})"
    print(f"VIES: сверка работает (ответили {', '.join(_alive)}; молчат {', '.join(_down) or '—'})")
    assert asyncio.run(verify("DE000000000")) is False
    print("VIES: выдуманный номер отвергается")
