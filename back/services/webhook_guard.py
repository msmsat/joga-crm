"""Общее правило ответа на вебхук Stripe: когда 200 — ложь.

Обе платёжные системы продукта — биллинг платформы (`routers/billing/webhook.py`)
и касса студий на Connect (`routers/checkout/stripe_pay.py`) — принимают события
Stripe и обязаны различать ДВА исхода, которые в коде выглядели одинаково:

* «событие не наше» — законный исход. Stripe шлёт события по всему аккаунту,
  чужие среди них норма, ретраить их незачем: отвечаем 200.
* «не смогли прочитать, чьё это событие» — совсем другое. Ответив 200, мы
  говорим Stripe «принято», ретрая не будет, и событие теряется НАВСЕГДА.
  По `invoice.paid` это «деньги взяли, тариф не включили»; по `charge.refunded`
  и `charge.dispute.closed` — «деньги вернули, доступ не отобрали».

Оба случая давали один и тот же `None` (нет идентификатора → поиск в базе не
находит строку → тихий выход), поэтому идентификаторы проверяются ОТДЕЛЬНО и
раньше поиска. Не найдено по прочитанному идентификатору — 200. Читать было
нечего — исключение, 500 и ретрай Stripe трое суток.

Модуль общий именно для того, чтобы правило не разъехалось: две копии одного
инварианта расходятся молча, а разница здесь стоит потерянной оплаты.
"""


class MalformedEvent(Exception):
    """Денежное событие, из которого не читается то, по чему его можно опознать.

    Ловят его общие `except` диспетчеров обоих вебхуков — там же, где ловится
    любой другой сбой обработки, и с тем же исходом: 500 под ретрай Stripe.
    Повтор безопасен: все хендлеры идемпотентны.
    """


def require(condition, event: str, obj, detail: str) -> None:
    """Денежное событие обязано нести то, по чему его можно опознать.

    `condition` ложно — значит поле, без которого решение принять нельзя, не
    прочиталось. Это не повод для тихого выхода.
    """
    if not condition:
        raise MalformedEvent(
            f"{event}: {detail} (объект {getattr(obj, 'id', None) or '<без id>'})"
        )


if __name__ == "__main__":
    # Самопроверка модуля: `python -m services.webhook_guard`
    ok = object()
    require(ok, "invoice.paid", None, "не должно сработать")
    try:
        require(None, "invoice.paid", None, "нет клиента")
    except MalformedEvent as exc:
        assert "invoice.paid" in str(exc) and "<без id>" in str(exc), exc
    else:
        raise AssertionError("пустое условие обязано поднимать MalformedEvent")

    class _Obj:
        id = "in_1"

    try:
        require(False, "charge.refunded", _Obj(), "нет платежа")
    except MalformedEvent as exc:
        assert "in_1" in str(exc), exc
    print("services/webhook_guard.py: ok")
