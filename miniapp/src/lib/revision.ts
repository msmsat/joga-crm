import { useSyncExternalStore } from 'react';

/**
 * Версия данных о занятиях: брони, отмены, присоединения к кофе.
 *
 * Разделы кабинета больше не пересобираются при переключении вкладок — App
 * держит уже открытые в DOM (иначе каждый тап по меню стоил скелета вместо
 * данных, повторного запроса и повторного проигрыша всех анимаций входа).
 * Вместе с пересборкой ушёл и способ узнавать о чужих изменениях: раньше
 * страница перечитывала данные просто потому, что монтировалась заново.
 *
 * Теперь об изменении объявляют явно. Запись с главной поднимает версию — и
 * расписание с «моими занятиями» перечитывают своё, хотя никуда не уходили.
 *
 * Модуль, а не контекст: подписчикам нужно одно число, а провайдер вокруг
 * приложения перерисовывал бы весь каркас на каждую бронь.
 */
let version = 0;

const listeners = new Set<() => void>();

function subscribe(onChange: () => void): () => void {
  listeners.add(onChange);
  return () => {
    listeners.delete(onChange);
  };
}

/** Данные о занятиях изменились — открытые разделы перечитают свои списки. */
export function bumpLessons(): void {
  version += 1;
  listeners.forEach((notify) => notify());
}

/** Версия для зависимостей эффекта: сменилась — раздел перечитывает данные. */
export function useLessonsVersion(): number {
  return useSyncExternalStore(subscribe, () => version);
}
