#!/bin/bash
# Ежедневный бэкап базы Velora. Ставится в cron ОДИН раз — см. DEPLOY.md, раздел
# «Бэкап базы». Запускается с хоста, не из контейнера: если Docker лёг, cron всё
# равно отработает и запишет в лог, что бэкапа сегодня нет.
#
# ponytail: копии лежат на том же диске, что и база — переживают `down -v`,
# порчу тома и неудачную миграцию, но не смерть диска. Нужна защита от неё —
# добавить `gcloud storage cp "$OUT" gs://<бакет>/` последней строкой.
set -euo pipefail

DIR="${VELORA_BACKUP_DIR:-$HOME/velora-backups}"
KEEP_DAYS="${VELORA_BACKUP_KEEP_DAYS:-14}"
# Каталог проекта берём от самого скрипта: cron стартует с домашнего каталога,
# и `docker compose` без этого не нашёл бы docker-compose.yml.
cd "$(dirname "$(readlink -f "$0")")"

mkdir -p "$DIR"
OUT="$DIR/velora-$(date +%F-%H%M).sql.gz"
TMP="$OUT.tmp"

# pipefail обязателен: без него падение pg_dump скрывается нулевым кодом gzip,
# и в каталог ложится аккуратный архив пустоты.
docker compose exec -T db pg_dump -U velora velora | gzip > "$TMP"

# Пустой дамп — это провал, просто молчаливый: gzip от пустого потока весит
# около двадцати байт, и никакой код возврата на это не пожалуется.
SIZE=$(wc -c < "$TMP")
if [ "$SIZE" -lt 1000 ]; then
  rm -f "$TMP"
  echo "$(date -Is) БЭКАП ПРОВАЛЕН: дамп $SIZE байт, это пустышка" >&2
  exit 1
fi

# Переименование только после проверки: оборванный дамп не должен лежать под
# именем годного — именно его возьмут при восстановлении и узнают о беде там.
mv "$TMP" "$OUT"

# Ротация ТОЛЬКО после успешной записи. Стой она выше, череда падений тихо
# съела бы все старые копии и оставила пустой каталог.
find "$DIR" -name 'velora-*.sql.gz' -mtime "+$KEEP_DAYS" -delete

echo "$(date -Is) бэкап ок: $OUT ($SIZE байт)"
